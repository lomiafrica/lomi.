const PHONE_AUTH_COUNTRY_SET = new Set<string>(PHONE_AUTH_COUNTRIES);

/** True when this country can receive a lomi. login code. */
export function isPhoneAuthCountry(code: string | undefined): boolean {
  return code !== undefined && PHONE_AUTH_COUNTRY_SET.has(code);
}

export function phoneAuthDial(code: CountryCode): string {
  return `+${getCountryCallingCode(code)}`;
}
